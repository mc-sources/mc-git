#!/usr/bin/env node
// scripts/build-notice-npm.mjs
//
// Génère docs/THIRD-PARTY-NOTICES-npm.md à partir du JSON produit par
// license-checker-rseidelsohn.
//
// Usage :
//   npx license-checker-rseidelsohn --production --json \
//     | node scripts/build-notice-npm.mjs > docs/THIRD-PARTY-NOTICES-npm.md
//
// Voir ANA-0001/T-0006 §7 pour le format de sortie attendu.

import { readFileSync } from "node:fs";

const raw = readFileSync(0, "utf-8");
const packages = JSON.parse(raw);

const entries = Object.entries(packages).sort(([a], [b]) => a.localeCompare(b));

const header = `# Third-Party Notices — npm dependencies

This file lists all npm runtime dependencies of Mc-Git and their licenses,
as required by their respective license terms.

The license of Mc-Git itself is **GPL-3.0-only** — see [\`LICENSE\`](../LICENSE).

Generated by \`scripts/build-notice-npm.mjs\` from the output of
\`license-checker-rseidelsohn --production\`.

---

`;

process.stdout.write(header);

for (const [key, info] of entries) {
    const at = key.lastIndexOf("@");
    const name = at > 0 ? key.slice(0, at) : key;
    const version = at > 0 ? key.slice(at + 1) : "unknown";
    const license = info.licenses ?? "UNKNOWN";
    const repo = info.repository ?? null;
    const licenseFile = info.licenseFile ?? null;

    let text = null;
    if (licenseFile) {
        try {
            text = readFileSync(licenseFile, "utf-8").replace(/\r\n?/g, "\n");
        } catch {
            text = null;
        }
    }

    process.stdout.write(`## ${name} v${version}\n\n`);
    process.stdout.write(`**License** : ${license}\n\n`);
    if (repo) process.stdout.write(`**Repository** : ${repo}\n\n`);
    if (text) {
        process.stdout.write("```text\n");
        process.stdout.write(text);
        if (!text.endsWith("\n")) process.stdout.write("\n");
        process.stdout.write("```\n\n");
    } else {
        process.stdout.write("_(no license text file available)_\n\n");
    }
    process.stdout.write("---\n\n");
}
